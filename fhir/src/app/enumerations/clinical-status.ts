/** A `Condition.clinicalStatus` code as the sandbox sent it. Active, recurrence, and relapse count as active. */
export enum ClinicalStatus {
  Active = 'active',
  Recurrence = 'recurrence',
  Relapse = 'relapse',
  Inactive = 'inactive',
  Remission = 'remission',
  Resolved = 'resolved',
  Unknown = 'unknown',
}
